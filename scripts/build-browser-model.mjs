// Generated public model modules contain pure calculations only, no credentials,
// database access, connector code or server authentication code.
import {mkdir,copyFile,readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const hash=createHash('sha256');
for(const name of ['analysis','waiver-plan','decision-outcomes','constants','weights','forecast'])hash.update(await readFile(new URL(`../src/${name}.js`,import.meta.url)));
hash.update(await readFile(new URL('../pipeline/models/opportunity-v1.json',import.meta.url)));
const revision=hash.digest('hex');
await writeFile(new URL('../src/model-revision.js',import.meta.url),`// Generated by build:model. Revision identifies the exact frozen calculation code.\nexport const MODEL_REVISION='${revision}';\n`);
await mkdir(new URL('../public/model/',import.meta.url),{recursive:true});
for(const name of ['analysis','decisions','constants','weights','news-format','waiver-plan','decision-outcomes','model-revision','forecast'])await copyFile(new URL(`../src/${name}.js`,import.meta.url),new URL(`../public/model/${name}.js`,import.meta.url));
console.log('Built shared browser calculation/format modules.');
// Append-only public archives contain pure math only. Keep previous directories
// in version control so future deployments can still replay earlier decisions.
const archive=new URL(`../public/model-history/${revision.slice(0,12)}/`,import.meta.url);
await mkdir(archive,{recursive:true});
for(const name of ['analysis','waiver-plan','decision-outcomes','constants','weights','model-revision','forecast'])await copyFile(new URL(`../src/${name}.js`,import.meta.url),new URL(`${name}.js`,archive));
