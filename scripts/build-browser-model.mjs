// Generated public model modules contain pure calculations only, no credentials,
// database access, connector code or server authentication code.
import {mkdir,copyFile,readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const hash=createHash('sha256');
for(const name of ['analysis','waiver-plan','decision-outcomes','constants','weights'])hash.update(await readFile(new URL(`../src/${name}.js`,import.meta.url)));
await writeFile(new URL('../src/model-revision.js',import.meta.url),`// Generated by build:model. Revision identifies the exact frozen calculation code.\nexport const MODEL_REVISION='${hash.digest('hex')}';\n`);
await mkdir(new URL('../public/model/',import.meta.url),{recursive:true});
for(const name of ['analysis','decisions','constants','weights','news-format','waiver-plan','decision-outcomes','model-revision'])await copyFile(new URL(`../src/${name}.js`,import.meta.url),new URL(`../public/model/${name}.js`,import.meta.url));
console.log('Built shared browser calculation/format modules.');
